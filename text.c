#include "core.h"
#include "version.h"

#include <stdio.h>
#include <math.h>

static void engprop(Laminate *pl);
static void matrices(Laminate *pl);
static void _fea(Laminate *pl);

void text_out(Laminate *pl, bool eng, bool mat, bool fea)
{
  printf("\nGenerated by lamprop version %s\n", VERSION);
  printf("laminate: %s\n", sv8cstring(pl->name));
  printf("thickness: %.2f mm, density: %4.2f g/cm³\n",
         pl->thickness, pl->ρ);
  printf("fiber volume fraction: %4.1f%%, ", 100*pl->vf);
  printf("fiber weight fraction: %4.1f%%\n", 100*pl->wf);
  printf("laminate weight: %.0f g/m², ", pl->fiber_weight + pl->resin_weight);
  printf("resin consumption: %.0f g/m²\n", pl->resin_weight);
  printf("num weight angle   vf fiber\n");
  printf("    [g/m²]   [°]  [%%]\n");
  for (int32_t k = 0; k < pl->nlayers; k++) {
    Lamina *la = pl->layers + k;
    printf("%3d %6g %5g %4.3g ", k+1, la->fiber_weight, 180*la->angle/M_PI, 100*la->vf);
    printf("%s\n", sv8cstring(la->f.name));
  }
  if (eng) {
    engprop(pl);
  }
  if (mat) {
    matrices(pl);
  }
  if (fea) {
    _fea(pl);
  }
}

void engprop(Laminate *pl)
{
  puts("In-plane engineering properties:");
  printf("E_x  = %.0f MPa, E_y  = %.0f MPa, E_z  = %.0f MPa\n",
         pl->Ex, pl->Ey, pl->Ez);
  printf("G_xy  = %.0f MPa, G_xz  = %.0f MPa, G_yz  = %.0f MPa\n",
         pl->Gxy, pl->Gxz, pl->Gyz);
  printf("ν_xy = %7.5f\n", pl->νxy);
  printf("α_x =  %9.4g K⁻¹, α_y =  %9.4g K⁻¹\n", pl->αx, pl->αy);
  puts("Engineering properties derived from 3D stiffness matrix:");
  printf("E_x  = %.0f MPa, E_y  = %.0f MPa, E_z  = %.0f MPa\n",
         pl->tEx, pl->tEy, pl->tEz);
  printf("G_xy  = %.0f MPa, G_xz  = %.0f MPa, G_yz  = %.0f MPa\n",
         pl->tGxy, pl->tGxz, pl->tGyz);
  printf("ν_xy = %.3f, ν_xz = %.3f, ν_yz = %.3f\n",  pl->tνxy, pl->tνxz, pl->tνyz);
}

void matrices(Laminate *pl)
{
  puts("In-plane stiffness (ABD) matrix:");
  for (int32_t r = 0; r < 6; r++) {
    printf("|% 10e % 10e % 10e % 10e % 10e % 10e |\n",
          pl->ABD[r][0], pl->ABD[r][1], pl->ABD[r][2],
          pl->ABD[r][3], pl->ABD[r][4], pl->ABD[r][5]);
  }
  puts("Transverse (H) stiffness matrix:");
  printf("|% 10e % 10e |\n", pl->H[0][0], pl->H[0][1]);
  printf("|% 10e % 10e |\n", pl->H[1][0], pl->H[1][1]);
  puts("3D stiffness tensor [C], contracted notation:");
  puts("(indices for stress/strain are in the order 11, 22, 33, 23, 13, 12)");
  for (int32_t r = 0; r < 6; r++) {
    printf("|% 10e % 10e % 10e % 10e % 10e % 10e |\n",
          pl->C[r][0], pl->C[r][1], pl->C[r][2],
          pl->C[r][3], pl->C[r][4], pl->C[r][5]);
  }
}

void _fea(Laminate *pl)
{
  puts("** Material data for CalculiX / Abaqus (SI units):");
  double D[6][6] = {0};
  toabaqusi(pl->C, D);
  printf("*MATERIAL,NAME=%s\n", sv8cstring(pl->name));
  if (isortho(pl->C)) {
    puts("*ELASTIC,TYPE=ORTHO");
    printf("%.4g,%.4g,%.4g,", D[0][0], D[0][1], D[1][1]);
    printf("%.4g,%.4g,%.4g,", D[0][2], D[1][2], D[2][2]);
    printf("%.4g,%.4g,\n", D[3][3], D[4][4]);
    printf("%.4g,293\n", D[5][5]);
  } else {
    puts("*ELASTIC,TYPE=ANISO");
    printf("%.4g,%.4g,%.4g,", D[0][0], D[0][1], D[1][1]);
    printf("%.4g,%.4g,%.4g,", D[0][2], D[1][2], D[2][2]);
    printf("%.4g,%.4g,\n", D[0][3], D[1][3]);
    printf("%.4g,%.4g,%.4g,", D[2][3], D[3][3], D[0][4]);
    printf("%.4g,%.4g,%.4g,", D[1][4], D[2][4], D[3][4]);
    printf("%.4g,%.4g,\n", D[4][4], D[0][5]);
    printf("%.4g,%.4g,%.4g,", D[1][5], D[2][5], D[3][5]);
    printf("%.4g,%.4g,293\n", D[4][5], D[5][5]);
  }
  puts("*DENSITY");
  printf("%.0f\n", pl->ρ*1000);
}
