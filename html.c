// Print a formatted row from a matrix.
static void pr(int n, double mat[n][n], int row, FILE *outfile)
{
  Sbuf b = {0};
  sbuf_appends(&b, "          <td>");
  for (int32_t j = 0; j < n; j++) {
    double num = mat[row][j];
    if (fpclassify(num) == FP_ZERO || (-1e-7 <= num && num <= 1e-7 )) {
      sbuf_appends(&b, "0");
    } else if (isnan(num)) {
      sbuf_appends(&b, "NaN");
    } else if (isinf(num)) {
      uint8_t inf[4] = {0xE2, 0x88, 0x9E, 0};
      sbuf_appends(&b, (void*)inf);
    } else {
      sbuf_printf(&b, "%-10.4g", num);
    }
    if (j < (n - 1)) {
      sbuf_appends(&b, "</td><td>");
    }
  }
  sbuf_appends(&b, "</td>");
  sbuf_fputs(&b, outfile);
}

void matrices(Laminate *pl, FILE *outfile)
{
  char *fstr[6] = {
    "<td>N<sub>x</sub></td>",
    "<td>N<sub>y</sub></td>",
    "<td>N<sub>xy</sub></td>",
    "<td>M<sub>x</sub></td>",
    "<td>M<sub>y</sub></td>",
    "<td>M<sub>xy</sub></td>"
  };
  char *dstr[6] = {
    "<td>&epsilon;<sub>x</sub></td>",
    "<td>&epsilon;<sub>y</sub></td>",
    "<td>&gamma;<sub>xy</sub></td>",
    "<td>&kappa;<sub>x</sub></td>",
    "<td>&kappa;<sub>y</sub></td>",
    "<td>&kappa;<sub>xy</sub></td>",
  };
  fputs("<tr>\n", outfile);
  fputs("<!-- second row, stiffness or ABD matrix -->\n", outfile);
  fputs("<td colspan=\"2\">\n", outfile);
  fputs("<table border=\"1\" frame=\"vsides\" rules=\"groups\" cellpadding=\"5%\">\n", outfile);
  fputs("<caption><strong>In-plane stiffness (ABD) matrix</strong></caption>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"6\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<tbody align=\"center\">\n", outfile);
  fputs("<tr>\n", outfile);
  fputs(fstr[0], outfile);
  fputs("<td rowspan=\"6\">=</td>\n", outfile);
  pr(6, pl->ABD, 0, outfile);
  fputs("<td rowspan=\"6\">&times;</td>\n", outfile);
  fputs(dstr[0], outfile);
  fputs("</tr>\n", outfile);
  for (int32_t r = 1; r < 6; r++) {
    fputs("<tr>\n", outfile);
    fputs(fstr[r], outfile);
    pr(6, pl->ABD, r, outfile);
    fputs(dstr[r], outfile);
    fputs("</tr>\n", outfile);
  }
  fputs("</tbody>\n", outfile);
  fputs("</table>\n", outfile);
  fputs("</td>\n", outfile);
  fputs("</tr>\n", outfile);
  fputs("<tr>\n", outfile);
  fputs("<!-- third row, transverse stiffness or H matrix -->\n", outfile);
  fputs("<td colspan=\"2\">\n", outfile);
  fputs("<table border=\"1\" frame=\"vsides\" rules=\"groups\" cellpadding=\"5%\">\n", outfile);
  fputs("<caption><strong>Transverse stiffness (H) matrix</strong></caption>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"2\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<tbody align=\"center\">\n", outfile);
  fputs("<tr>\n", outfile);
  fputs("<td>V<sub>y</sub></td>\n", outfile);
  fputs("<td rowspan=\"2\">=</td>\n", outfile);
  pr(2, pl->H, 0, outfile);
  fputs("<td rowspan=\"2\">&times;</td>\n", outfile);
  fputs("<td>&gamma;<sub>yz</sub></td>\n", outfile);
  fputs("</tr>\n", outfile);
  fputs("<tr>\n", outfile);
  fputs("<td>V<sub>x</sub></td>\n", outfile);
  pr(2, pl->H, 1, outfile);
  fputs("<td>&gamma;<sub>xz</sub></td>\n", outfile);
  fputs("</tr>\n", outfile);
  fputs("</tbody>\n", outfile);
  fputs("</table>\n", outfile);
  fputs("</td>\n", outfile);
  fputs("</tr>\n", outfile);
  char *fstr2[6] = {
    "<td>&sigma;<sub>11</sub></td>",
    "<td>&sigma;<sub>22</sub></td>",
    "<td>&sigma;<sub>33</sub></td>",
    "<td>&sigma;<sub>23</sub></td>",
    "<td>&sigma;<sub>13</sub></td>",
    "<td>&sigma;<sub>12</sub></td>",
  };
  char *dstr2[6] = {
    "<td>&epsilon;<sub>11</sub></td>",
    "<td>&epsilon;<sub>22</sub></td>",
    "<td>&epsilon;<sub>33</sub></td>",
    "<td>2&epsilon;<sub>23</sub></td>",
    "<td>2&epsilon;<sub>13</sub></td>",
    "<td>2&epsilon;<sub>12</sub></td>",
  };
  fputs("<tr>\n", outfile);
  fputs("<!-- next row, stiffness tensor -->\n", outfile);
  fputs("<td colspan=\"2\">\n", outfile);
  fputs("<table border=\"1\" frame=\"vsides\" rules=\"groups\" cellpadding=\"5%\">\n", outfile);
  fputs("<caption><strong>3D stiffness (C) tensor, contracted notation</strong></caption>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"6\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<colgroup span=\"1\"></colgroup>\n", outfile);
  fputs("<tbody align=\"center\">\n", outfile);
  fputs("<tr>\n", outfile);
  fputs(fstr2[0], outfile);
  fputs("<td rowspan=\"6\">=</td>\n", outfile);
  pr(6, pl-> C, 0, outfile),
  fputs("<td rowspan=\"6\">&times;</td>\n", outfile);
  fputs(dstr2[0], outfile);
  fputs("</tr>\n", outfile);
  for (int32_t r = 1; r < 6; r++) {
    fputs("<tr>\n", outfile);
    fputs(fstr2[r], outfile);
    pr(6, pl->C, r, outfile);
    fputs(dstr2[r], outfile);
    fputs("</tr>\n", outfile);
  }
  fputs("</tbody>\n", outfile);
  fputs("</table>\n", outfile);
  fputs("</td>\n", outfile);
  fputs("</tr>\n", outfile);
}
