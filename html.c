void html_out(Laminate *pl, Options opt)
{
  assert(pl != 0);
  fputs("<!DOCTYPE html>\n", opt.outfile);
  fputs("<html lang=\"en-US\">\n", opt.outfile);
  fputs("<head><meta charset=\"UTF-8\">"
       "<meta name=\"description\" content=\"lamprop output\">", opt.outfile);
  fputs("<title>lamprop output</title>\n", opt.outfile);
  fputs("</head>\n", opt.outfile);
  fputs("<body>\n", opt.outfile);
  fputs("<!-- outer table -->\n", opt.outfile);
  fputs("<table cellpadding=\"10%\">\n", opt.outfile);
  fprintf(opt.outfile, "<caption><strong>Properties of %s</strong></caption>\n", sv8cstring(pl->name));
  fputs("<tbody align=\"center\">\n", opt.outfile);
  fputs("<tr><td  align=\"center\" colspan=\"2\">Generated by "
       LONG_VERSION".</td></tr>\n", opt.outfile);
  fputs("<!-- first row; tables -->\n", opt.outfile);
  fputs("<tr><td>\n", opt.outfile);
  fputs("<table border=\"1\" frame=\"hsides\"\n", opt.outfile);
  fputs("rules=\"groups\" cellpadding=\"5%\">\n", opt.outfile);
  fputs("<caption><strong>Laminate stacking</strong></caption>\n", opt.outfile);
  fputs("<thead align=\"right\">\n", opt.outfile);
  fputs("<tr><td>Layer</td><td>weight</td>\n", opt.outfile);
  fputs("<td>angle</td><td>vf</td><td align=\"left\">fiber type</td></tr>\n", opt.outfile);
  fputs("<tr><td></td><td>[g/m&sup2;]</td><td>[&deg;]</td><td>[%]</td></tr>\n", opt.outfile);
  fputs("</thead>\n", opt.outfile);
  fputs("<tbody align=\"right\">\n", opt.outfile);
  for (int32_t k = 0; k < pl->nlayers; k++) {
    Lamina *la = pl->layers + k;
    if (la->comment.data && la->comment.len) {
      fputs("<tr>\n", opt.outfile);
      fprintf(opt.outfile, "<td  align=\"left\" colspan=\"5\">%s</td>\n", sv8cstring(la->comment));
      fputs("</tr>\n", opt.outfile);
    } else if (la->symm) {
      fputs("<tr>\n", opt.outfile);
      fputs("<td  align=\"left\" colspan=\"5\">&horbar; symmetry line &horbar;</td>\n", opt.outfile);
      fputs("</tr>\n", opt.outfile);
    }
    fputs("<tr>\n", opt.outfile);
    fprintf(opt.outfile, "<td>%3d</td><td>%6g</td><td>%5g</td>", k + 1, la->fiber_weight,
           180 * la->angle / M_PI);
    fprintf(opt.outfile, "<td>%4.3g</td><td align=\"left\">%s</td>\n",
           100 * la->vf, sv8cstring(la->f.name));
    fputs("</tr>\n", opt.outfile);
  }
  fputs("</tbody>\n", opt.outfile);
  fputs("</table>\n", opt.outfile);
  fputs("</td>\n", opt.outfile);
  fputs("<td>\n", opt.outfile);
  fputs("<table border=\"1\" frame=\"hsides\" rules=\"groups\" cellpadding=\"5%\">\n", opt.outfile);
  fputs("<caption><strong>Physical properties</strong></caption>\n", opt.outfile);
  fputs("<thead align=\"right\">\n", opt.outfile);
  fputs("<tr><td>Property</td><td>Value</td><td align=\"left\">Dimension</td></tr>\n", opt.outfile);
  fputs("</thead>\n", opt.outfile);
  fputs("<tbody align=\"right\">\n", opt.outfile);
  fprintf(opt.outfile, "<tr><td>v<sub>f</sub></td><td>%4.1f</td><td align=\"left\">%%</td></tr>\n",
         100 * pl->vf);
  fprintf(opt.outfile, "<tr><td>w<sub>f</sub></td><td>%4.1f</td><td align=\"left\">%%</td></tr>\n",
         100 * pl->wf);
  fprintf(opt.outfile, "<tr><td>thickness</td><td>%.2f</td><td align=\"left\">mm</td></tr>\n",
         pl->thickness);
  fprintf(opt.outfile, "<tr><td>density</td><td>%4.2f</td><td align=\"left\">g/cm&sup3;</td></tr>\n",
         pl->ρ);
  fprintf(opt.outfile, "<tr><td>weight</td><td>%.0f</td><td align=\"left\">g/m&sup2;</td></tr>\n",
         pl->fiber_weight + pl->resin_weight);
  fprintf(opt.outfile, "<tr><td>resin</td><td>%.0f</td><td align=\"left\">g/m&sup2;</td></tr>\n",
         pl->resin_weight);
  if (opt.eng) {
    engprop(pl, opt.outfile);
  }
  fputs("</tbody>\n", opt.outfile);
  fputs("</table>\n", opt.outfile);
  fputs("</td>\n", opt.outfile);
  fputs("</tr>\n", opt.outfile);
  if (opt.matrix) {
    matrices(pl, opt.outfile);
  }
  if (opt.fea) {
    fputs("<tr>\n", opt.outfile);
    fputs("<!-- next row, stiffness tensor -->\n", opt.outfile);
    fputs("<td colspan=\"2\" align=\"left\">\n", opt.outfile);
    fputs("<pre>\n", opt.outfile);
    text_fea(pl, opt.outfile);
    fputs("</pre>\n", opt.outfile);
    fputs("</td>\n", opt.outfile);
    fputs("</tr>\n", opt.outfile);
  }
  fputs("\n", opt.outfile);
  fflush(opt.outfile);
}

